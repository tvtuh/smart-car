                                                                    //   （和原来手动固定值 150 基本一致）
                                                                    //   调大 = 阈值更高 = 图像更黑；调小 = 图像更白
#define IMAGE_NEAR_REF_MIN              ( 100 )                     // 参考白点低于本值就认为这块不是赛道，
                                                                    //   保留上一次阈值（防摄像头被挡/全黑时乱跳）
#define IMAGE_NEAR_REF_SMOOTH           ( 1 )                       // 1 = 对阈值做一阶平滑(防逐帧抖动)


