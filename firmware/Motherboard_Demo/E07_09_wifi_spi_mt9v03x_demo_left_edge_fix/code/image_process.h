//------------------------------------------------------------------------------------------------------------------
// 近端参考白点阈值（IMAGE_THRESHOLD_MODE_NEAR_REF）的参数
//
//   思路（逐飞直播"搜线算法优化"第 1 条）：最靠近车身那几行图像【一定全是赛道】，
//   取它们的灰度均值当"参考白点"，阈值按这个白点的比例取。
//   好处：换场地、换光线、镜头脏了、灯变了，阈值自己跟着走，不用再手调固定值。
//   代价：取样区只有 8×108 = 864 个像素，每帧算一次可以忽略不计。
//
//   取哪一块：行 110~117（避开最下面两行 —— 实车发现第 119 行中心偶尔压着一小块暗斑），
//             列 40~147（避开画面左右边缘，那两边可能已经是别的赛道/背景）。
//   安全兜底：这一块的均值太低（摄像头被挡/全黑/车冲出赛道）就保留上一次的阈值，不跟着跳。
//------------------------------------------------------------------------------------------------------------------
#define IMAGE_NEAR_REF_ROW1             ( 110 )                     // 参考白点取样区 上边界(行)
#define IMAGE_NEAR_REF_ROW2             ( 117 )                     //                    下边界(行)
#define IMAGE_NEAR_REF_COL1             ( 40 )                      //                    左边界(列)
#define IMAGE_NEAR_REF_COL2             ( 147 )                     //                    右边界(列)
#define IMAGE_NEAR_REF_RATIO            ( 0.62f )                   // 阈值 = 参考白点 * 本比例
